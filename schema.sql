-- Disable prompt echoing and pause on SQL error (optional)
SET FEEDBACK ON;

-- 1. CHAT TABLE (Required dependency for CHAT_MEMBER and MESSAGE)
CREATE TABLE CHAT (
    CHAT_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CHAT_TYPE           VARCHAR2(20) DEFAULT 'DIRECT' CHECK (CHAT_TYPE IN ('DIRECT', 'GROUP')),
    TITLE               VARCHAR2(100),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. USERS TABLE
CREATE TABLE USERS (
    USER_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    USERNAME            VARCHAR2(50) NOT NULL UNIQUE,
    EMAIL               VARCHAR2(150) UNIQUE,
    PHONE_NUMBER        VARCHAR2(20) NOT NULL UNIQUE,
    PASSWORD_HASH       VARCHAR2(255) NOT NULL,
    FULL_NAME           VARCHAR2(100),
    PROFILE_PICTURE     VARCHAR2(500),
    BIO                 VARCHAR2(250),
    DATE_OF_BIRTH       DATE,
    GENDER              VARCHAR2(10),
    LAST_SEEN           TIMESTAMP,
    IS_ONLINE           CHAR(1) DEFAULT 'N' CHECK (IS_ONLINE IN ('Y', 'N')),
    ACCOUNT_STATUS      VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (ACCOUNT_STATUS IN ('ACTIVE', 'BLOCKED', 'DELETED')),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT          TIMESTAMP
);

-- 3. CONTACTS TABLE
CREATE TABLE CONTACTS (
    CONTACT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER NOT NULL,
    CONTACT_USER_ID     NUMBER NOT NULL,
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_CONTACT_USER FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CONTACT_PERSON FOREIGN KEY(CONTACT_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UK_CONTACT UNIQUE(USER_ID, CONTACT_USER_ID),
    CONSTRAINT CK_CONTACT_NOT_SELF CHECK (USER_ID <> CONTACT_USER_ID)
);

CREATE INDEX IDX_CONTACT_USER ON CONTACTS(USER_ID);
CREATE INDEX IDX_CONTACT_PERSON ON CONTACTS(CONTACT_USER_ID);

-- 4. CHAT_MEMBER TABLE
CREATE TABLE CHAT_MEMBER (
    MEMBER_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CHAT_ID             NUMBER NOT NULL,
    USER_ID             NUMBER NOT NULL,
    ROLE                VARCHAR2(20) DEFAULT 'MEMBER' CHECK (ROLE IN ('OWNER','ADMIN','MEMBER')),
    JOINED_AT           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LEFT_AT             TIMESTAMP,
    IS_MUTED            CHAR(1) DEFAULT 'N' CHECK (IS_MUTED IN ('Y','N')),
    IS_PINNED           CHAR(1) DEFAULT 'N' CHECK (IS_PINNED IN ('Y','N')),
    IS_ARCHIVED         CHAR(1) DEFAULT 'N' CHECK (IS_ARCHIVED IN ('Y','N')),
    CONSTRAINT FK_CM_CHAT FOREIGN KEY (CHAT_ID) REFERENCES CHAT(CHAT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_CM_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UK_CHAT_MEMBER UNIQUE (CHAT_ID, USER_ID)
);

CREATE INDEX IDX_CM_USER ON CHAT_MEMBER(USER_ID);
CREATE INDEX IDX_CM_CHAT ON CHAT_MEMBER(CHAT_ID);

-- 5. MESSAGE TABLE
CREATE TABLE MESSAGE (
    MESSAGE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CHAT_ID             NUMBER NOT NULL,
    SENDER_ID           NUMBER NOT NULL,
    REPLY_TO            NUMBER,
    MESSAGE_TYPE        VARCHAR2(20) DEFAULT 'TEXT' CHECK (MESSAGE_TYPE IN ('TEXT', 'IMAGE', 'VIDEO', 'AUDIO', 'DOCUMENT')),
    MESSAGE_TEXT        CLOB,
    IS_FORWARDED        CHAR(1) DEFAULT 'N' CHECK(IS_FORWARDED IN ('Y','N')),
    IS_EDITED           CHAR(1) DEFAULT 'N' CHECK(IS_EDITED IN ('Y','N')),
    SENT_AT             TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    EDITED_AT           TIMESTAMP,
    DELETED_FOR_ALL     CHAR(1) DEFAULT 'N' CHECK(DELETED_FOR_ALL IN ('Y','N')),
    FOREIGN KEY(CHAT_ID) REFERENCES CHAT(CHAT_ID) ON DELETE CASCADE,
    FOREIGN KEY(SENDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY(REPLY_TO) REFERENCES MESSAGE(MESSAGE_ID) ON DELETE SET NULL
);

CREATE INDEX IDX_MSG_CHAT_SENT ON MESSAGE(CHAT_ID, SENT_AT);
CREATE INDEX IDX_MSG_SENDER ON MESSAGE(SENDER_ID);
CREATE INDEX IDX_MSG_REPLY_TO ON MESSAGE(REPLY_TO);

-- 6. MESSAGE_DELETE TABLE
CREATE TABLE MESSAGE_DELETE (
    MESSAGE_ID          NUMBER NOT NULL,
    USER_ID             NUMBER NOT NULL,
    DELETED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_MESSAGE_DELETE PRIMARY KEY (MESSAGE_ID, USER_ID),
    CONSTRAINT FK_MD_MESSAGE FOREIGN KEY(MESSAGE_ID) REFERENCES MESSAGE(MESSAGE_ID) ON DELETE CASCADE,
    CONSTRAINT FK_MD_USER FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_MD_USER ON MESSAGE_DELETE(USER_ID);

-- 7. MESSAGE_STATUS TABLE
CREATE TABLE MESSAGE_STATUS (
    STATUS_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MESSAGE_ID          NUMBER NOT NULL,
    USER_ID             NUMBER NOT NULL,
    STATUS              VARCHAR2(20) CHECK(STATUS IN ('SENT','DELIVERED','SEEN')),
    STATUS_TIME         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(MESSAGE_ID) REFERENCES MESSAGE(MESSAGE_ID) ON DELETE CASCADE,
    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UK_MSG_STATUS UNIQUE(MESSAGE_ID, USER_ID)
);

CREATE INDEX IDX_STATUS_MSG ON MESSAGE_STATUS(MESSAGE_ID);
CREATE INDEX IDX_STATUS_USER ON MESSAGE_STATUS(USER_ID);

-- 8. ATTACHMENT TABLE
CREATE TABLE ATTACHMENT (
    ATTACHMENT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MESSAGE_ID          NUMBER NOT NULL,
    FILE_NAME           VARCHAR2(255),
    FILE_PATH           VARCHAR2(1000),
    FILE_TYPE           VARCHAR2(50),
    FILE_SIZE           NUMBER,
    UPLOADED_AT         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(MESSAGE_ID) REFERENCES MESSAGE(MESSAGE_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_ATTACHMENT_MSG ON ATTACHMENT(MESSAGE_ID);

-- 9. MESSAGE_REACTION TABLE
CREATE TABLE MESSAGE_REACTION (
    REACTION_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MESSAGE_ID          NUMBER NOT NULL,
    USER_ID             NUMBER NOT NULL,
    REACTION            VARCHAR2(20),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(MESSAGE_ID) REFERENCES MESSAGE(MESSAGE_ID) ON DELETE CASCADE,
    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UK_MSG_REACTION UNIQUE(MESSAGE_ID, USER_ID)
);

CREATE INDEX IDX_REACTION_MSG ON MESSAGE_REACTION(MESSAGE_ID);

-- 10. BLOCKED_USER TABLE
CREATE TABLE BLOCKED_USER (
    BLOCK_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER NOT NULL,
    BLOCKED_USER_ID     NUMBER NOT NULL,
    BLOCKED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    FOREIGN KEY(BLOCKED_USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT UK_BLOCK UNIQUE(USER_ID, BLOCKED_USER_ID),
    CONSTRAINT CK_BLOCK_NOT_SELF CHECK (USER_ID <> BLOCKED_USER_ID)
);

CREATE INDEX IDX_BLOCK_USER ON BLOCKED_USER(USER_ID);
CREATE INDEX IDX_BLOCK_BLOCKED ON BLOCKED_USER(BLOCKED_USER_ID);

-- 11. NOTIFICATION TABLE
CREATE TABLE NOTIFICATION (
    NOTIFICATION_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER NOT NULL,
    TITLE               VARCHAR2(100),
    BODY                VARCHAR2(300),
    IS_READ             CHAR(1) DEFAULT 'N' CHECK(IS_READ IN ('Y','N')),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_NOTIF_USER ON NOTIFICATION(USER_ID);

-- 12. USER_DEVICE TABLE
CREATE TABLE USER_DEVICE (
    DEVICE_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID             NUMBER NOT NULL,
    DEVICE_NAME         VARCHAR2(100),
    DEVICE_TYPE         VARCHAR2(30),
    FCM_TOKEN           VARCHAR2(500),
    LAST_LOGIN          TIMESTAMP,
    FOREIGN KEY(USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE INDEX IDX_DEVICE_USER ON USER_DEVICE(USER_ID);

COMMIT;